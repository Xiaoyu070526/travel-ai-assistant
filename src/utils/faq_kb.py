def match_faq(question: str) -> Optional[dict]:
    """关键词匹配本地 FAQ，命中返回条目，未命中返回 None"""
    q = question.lower()
    best: Optional[dict] = None
    best_score = 0
    for item in FAQ_KB:
        score = sum(1 for kw in item["keywords"] if kw.lower() in q)
        if score > best_score:
            best_score = score
            best = item
    # 至少命中 1 个关键词才认为命中，避免误判
    if best_score >= 1:
        return best
    return None


